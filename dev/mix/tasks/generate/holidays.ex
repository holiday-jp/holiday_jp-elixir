defmodule Mix.Tasks.Generate.Holidays do
  @moduledoc """
  Generate the holidays DB
  """

  use Mix.Task

  @shortdoc "Generate the holidays database"

  @impl true
  def run(_) do
    {:ok, _} = Application.ensure_all_started(:yamerl)
    src = Path.join([__DIR__, "..", "..", "..", "..", "holiday_jp", "holidays_detailed.yml"])
    dest = Path.expand("../../../../priv/holidays.exs", __DIR__)
    generate(src, dest)
  end

  @doc false
  def generate(src, dest) do
    documents =
      src
      |> String.to_charlist()
      |> :yamerl.decode_file(keep_duplicate_keys: true)

    entries =
      case documents do
        [] -> raise "holiday data is empty"
        [empty] when empty in [nil, :null, []] -> raise "holiday data is empty"
        [entries] when is_list(entries) -> entries
        _ -> raise "holiday data must contain one mapping"
      end

    holidays =
      entries
      |> Enum.map(fn {date, holiday} ->
        holiday = Map.new(holiday)

        {to_string(date), required_field!(holiday, ~c"week", date), required_field!(holiday, ~c"week_en", date),
         required_field!(holiday, ~c"name", date), required_field!(holiday, ~c"name_en", date)}
      end)
      |> Enum.sort_by(&elem(&1, 0))

    dates = Enum.map(holidays, &elem(&1, 0))

    if dates == [], do: raise("holiday data is empty")
    if length(dates) != length(Enum.uniq(dates)), do: raise("holiday data contains duplicate dates")
    Enum.each(dates, &Date.from_iso8601!/1)

    lines = Enum.map(holidays, &["  ", inspect(&1, limit: :infinity, printable_limit: :infinity), ",\n"])
    contents = ["# Generated by mix generate.holidays. Do not edit by hand.\n[\n", lines, "]\n"]
    temp = "#{dest}.#{System.pid()}.#{System.unique_integer([:positive])}.tmp"
    file = File.open!(temp, [:write, :binary, :exclusive])

    try do
      :ok = IO.binwrite(file, contents)
      :ok = File.close(file)
      File.rename!(temp, dest)
    after
      File.close(file)
      File.rm(temp)
    end
  end

  defp required_field!(holiday, key, date) do
    case holiday[key] do
      value when is_list(value) and value != [] ->
        text = to_string(value)
        if String.trim(text) == "", do: raise("empty #{key} for #{date}")
        text

      _ ->
        raise "missing or empty #{key} for #{date}"
    end
  end
end
